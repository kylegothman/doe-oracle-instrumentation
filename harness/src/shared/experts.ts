/**
 * The human expert whose answers to the 12 standard questions are the
 * baseline every subject is scored against (UC-5, Detailed Design Figure 10).
 * The expert's name is the only personal name the harness stores (NFR-7).
 */

/** How the expert's answers arrived. */
export enum ResponseSource {
  EMAIL = 'EMAIL',
  INTERVIEW = 'INTERVIEW',
}

/** Every response source, in the order the harness lists them. */
export const RESPONSE_SOURCES: readonly ResponseSource[] = [ResponseSource.EMAIL, ResponseSource.INTERVIEW]

/** True when value is one of the response sources. Use it on anything that crossed the IPC bridge. */
export function isResponseSource(value: unknown): value is ResponseSource {
  return typeof value === 'string' && (RESPONSE_SOURCES as readonly string[]).includes(value)
}

/**
 * One expert, with the turnaround stored once (not per answer). The two
 * timestamps are entered by the Researcher from the email exchange, so they
 * may be missing until the reply arrives; turnaroundMs is then null too.
 */
export interface Expert {
  /** UUID, generated by whoever creates the expert. */
  expertId: string
  name: string
  source: ResponseSource
  /** When the questions were sent to the expert, ISO 8601 UTC with milliseconds. */
  outreachTs: string | null
  /** When the expert's first answer arrived, ISO 8601 UTC with milliseconds. */
  firstAnswerTs: string | null
  /** firstAnswerTs minus outreachTs, in milliseconds. */
  turnaroundMs: number | null
}

/**
 * One answer from an expert to one question. Answers are never overwritten:
 * replacing one saves a new ExpertResponse with the old one's test number
 * and sets the old one's supersededBy to the new responseId. Only active
 * answers (supersededBy null) are exported and scored.
 */
export interface ExpertResponse {
  responseId: number
  /**
   * From the same sequence as trials, so every exported row has a unique
   * Test #. A replacement takes over the answer it replaces' number, so a
   * revised answer keeps its Test #; the superseded answer's is then null.
   */
  testNumber: number | null
  expertId: string
  /** The harness session the answer was entered in. */
  sessionId: string
  questionNumber: number
  answerText: string
  /** UTF-8 byte length of answerText. The repository computes it on save. */
  sizeBytes: number
  /** The question's most significant terms, for the export's Keywords column. */
  keywords: string | null
  /** When the answer was entered into the harness, ISO 8601 UTC with milliseconds. */
  recordedAt: string
  /** The responseId of the answer that replaced this one; null while it is the active answer. */
  supersededBy: number | null
}
